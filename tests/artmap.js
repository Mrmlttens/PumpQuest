const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
const ctx={window:{}};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.resolve(__dirname,'../artmap.js'),'utf8'),ctx);
const m=ctx.window.PQ_ART;
assert(m.FRONT.upperChest.includes('M'), 'Real chest region defined');
assert(m.BACK.lats.includes('M'), 'Back-specific lats defined');
const ids=new Set([...Object.keys(m.FRONT),...Object.keys(m.BACK)]);
assert.equal(ids.size,19, 'Every one of the 19 tracked anatomy regions has a body hit-zone');
let labels={};for(const id of ids)labels[id]={label:id,status:'untracked',days:null};
labels.upperChest={label:'Upper chest',status:'hot',days:0};
labels.quads={label:'Quads',status:'cold',days:17};
const front=m.draw({side:'front',zones:labels,selected:'upperChest'});
const back=m.draw({side:'back',zones:labels});
assert(front.includes('champion-stormhorn-front.webp'));
assert(back.includes('champion-stormhorn-back.webp'));
assert(front.includes('state-hot'));
assert(front.includes('state-cold'));
assert(front.includes('data-action="artZone"'));
assert(front.includes('data-zone="upperChest"'));
assert(back.includes('data-zone="lats"'));
console.log('PASS: complete 19-zone cinematic art mapping, front/back, hot/cold and tap targets');